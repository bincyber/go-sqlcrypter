package aesgcm

import (
	"bytes"
	"crypto/aes"
	"crypto/cipher"
	"io"

	"github.com/pkg/errors"

	"github.com/bincyber/go-sqlcrypter"
)

// AESCrypter is an implementation of the Crypterer interface using
// 256-bit AES in Galois Counter Mode with support for key rotation.
//
// Ciphertext is stored as nonce (12 bytes) || ciphertext || tag (16 bytes).
// The nonce is generated inside crypto/cipher by cipher.NewGCMWithRandomNonce,
// which is the form the Go Cryptographic Module accepts when it enforces
// approved-only operation (GODEBUG=fips140=only). The layout is the same one
// earlier versions of this provider wrote with a caller-generated nonce, so
// data encrypted by any version decrypts with any other.
//
// Do not encrypt more than 2^32 values with a single DEK. See the README.
type AESCrypter struct {
	// current is AES GCM block cipher used to encrypt any new data
	// using the current data encryption key.
	current cipher.AEAD

	// previous is AES GCM block cipher used to decrypt old data
	// using the previous data encryption key.
	previous cipher.AEAD
}

// New initializes the AES GCM crypter with the provided data encryption key (DEK).
// To support key rotation, a previous DEK can optionally be provided. If the
// previous DEK is set, it is only used for decryption. Any new data is encrypted
// with the current DEK.
func New(key []byte, previousKey []byte) (sqlcrypter.Crypterer, error) {
	if len(key) != 32 {
		return nil, errors.Wrap(aes.KeySizeError(len(key)), "DEK is invalid")
	}

	current, err := newAEAD(key)
	if err != nil {
		return nil, err
	}

	var previous cipher.AEAD
	if previousKey != nil {
		if len(previousKey) != 32 {
			return nil, errors.Wrap(aes.KeySizeError(len(previousKey)), "previous DEK is invalid")
		}

		previous, err = newAEAD(previousKey)
		if err != nil {
			return nil, err
		}
	}

	return &AESCrypter{
		current:  current,
		previous: previous,
	}, nil
}

// newAEAD wraps the key in AES-GCM. It prefers cipher.NewGCMWithRandomNonce, which
// generates the nonce inside crypto/cipher. That constructor accepts only the
// standard library's AES block; toolchains that replace it (GOEXPERIMENT=boringcrypto)
// fall back to cipher.NewGCM with a nonce generated by this provider. Both produce
// the same stored layout.
func newAEAD(key []byte) (cipher.AEAD, error) {
	cipherBlock, err := aes.NewCipher(key)
	if err != nil {
		return nil, err
	}

	if aead, err := cipher.NewGCMWithRandomNonce(cipherBlock); err == nil {
		return aead, nil
	}

	aead, err := cipher.NewGCM(cipherBlock)
	if err != nil {
		return nil, errors.Wrap(err, "failed to create GCM wrapped block cipher")
	}

	return aead, nil
}

// Encrypt encrypts plaintext to ciphertext using the current DEK.
func (a *AESCrypter) Encrypt(w io.Writer, r io.Reader) error {
	if a.current == nil {
		return errors.New("AES-GCM was not initialized")
	}

	src := new(bytes.Buffer)
	_, err := src.ReadFrom(r)
	if err != nil {
		return errors.Wrap(err, "failed to read from io.Reader")
	}

	var blob []byte
	if a.current.NonceSize() == 0 {
		// cipher.NewGCMWithRandomNonce generates the nonce and prepends it.
		blob = a.current.Seal(nil, nil, src.Bytes(), nil) //nolint:gosec // G407: NewGCMWithRandomNonce generates the nonce and requires nil here
	} else {
		// Fallback AEAD: nonce first (12 bytes), then ciphertext including AEAD overhead.
		nonce, err := sqlcrypter.GenerateBytes(a.current.NonceSize())
		if err != nil {
			return errors.Wrap(err, "failed to generate random nonce")
		}

		blob = a.current.Seal(nonce, nonce, src.Bytes(), nil)
	}

	if _, err := w.Write(blob); err != nil {
		return errors.Wrap(err, "failed to write ciphertext")
	}

	return nil
}

// Decrypt decrypts ciphertext to plaintext. It first attempts to decrypt
// using the previous DEK if specified, followed by the current DEK.
func (a *AESCrypter) Decrypt(w io.Writer, r io.Reader) error {
	if a.current == nil {
		return errors.New("AES-GCM was not initialized")
	}

	src := new(bytes.Buffer)
	n, err := src.ReadFrom(r)
	if err != nil {
		return errors.Wrap(err, "failed to read from io.Reader")
	}

	// crypto/cipher.AEAD.Open panics if the nonce is not exactly NonceSize()
	// bytes long. bytes.Buffer.Next returns min(n, available), so guard the
	// input length before slicing. The minimum well-formed blob is the 12-byte
	// nonce plus the 16-byte authentication tag. For the random-nonce AEAD,
	// NonceSize() is 0 and Overhead() already counts the nonce; for the
	// fallback AEAD it is 12 and 16. Both sum to 28.
	minLen := int64(a.current.NonceSize() + a.current.Overhead())
	if n < minLen {
		return errors.New("failed to read ciphertext: minimum length not met")
	}

	// The random-nonce AEAD reads the nonce from the blob itself (NonceSize() == 0);
	// the fallback AEAD needs it split off.
	nonce := src.Next(a.current.NonceSize())
	ciphertext := src.Next(src.Len())

	// First attempt to decrypt using previous DEK if it's set in the provider
	var attempted bool
	if a.previous != nil {
		if plaintext, err := a.previous.Open(nil, nonce, ciphertext, nil); err == nil {
			return writePlaintext(w, plaintext)
		}

		attempted = true
	}

	// Decrypt using the current DEK
	plaintext, err := a.current.Open(nil, nonce, ciphertext, nil)
	if err != nil {
		if attempted {
			return errors.Wrap(err, "failed to decrypt ciphertext using current and previous DEK")
		}

		return errors.Wrap(err, "failed to decrypt ciphertext using current DEK")
	}

	return writePlaintext(w, plaintext)
}

func writePlaintext(w io.Writer, plaintext []byte) error {
	if _, err := w.Write(plaintext); err != nil {
		return errors.Wrap(err, "failed to write plaintext")
	}

	return nil
}

var _ sqlcrypter.Crypterer = (*AESCrypter)(nil)
