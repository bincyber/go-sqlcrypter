// legacyGCM returns the AES-GCM AEAD that versions of this provider before
// v0.4.0 used: cipher.NewGCM with a nonce chosen by the caller. The Go
// Cryptographic Module does not approve caller-chosen nonces, so under
// GODEBUG=fips140=only the constructor is wrapped in fips140.WithoutEnforcement.
// Only the constructor checks enforcement; Seal and Open do not. Outside only
// mode the wrapper is a no-op.
func legacyGCM(t *testing.T, key []byte) cipher.AEAD {
	t.Helper()

	block, err := aes.NewCipher(key)
	require.NoError(t, err)

	var aead cipher.AEAD
	fips140.WithoutEnforcement(func() {
		aead, err = cipher.NewGCM(block)
	})
	require.NoError(t, err)

	return aead
}

// legacySeal encrypts plaintext the way v0.3.0 did: a random 12-byte nonce
// generated by the caller, followed by ciphertext and tag.
func legacySeal(t *testing.T, key, plaintext []byte) []byte {
	t.Helper()

	aead := legacyGCM(t, key)
	nonce, err := sqlcrypter.GenerateBytes(aead.NonceSize())
	require.NoError(t, err)

	return aead.Seal(nonce, nonce, plaintext, nil)
}

// legacyOpen decrypts a blob the way v0.3.0 did: the first 12 bytes are the nonce.
func legacyOpen(t *testing.T, key, blob []byte) ([]byte, error) {
	t.Helper()

	aead := legacyGCM(t, key)
	if len(blob) < aead.NonceSize()+aead.Overhead() {
		return nil, errors.New("blob too short")
	}

	return aead.Open(nil, blob[:aead.NonceSize()], blob[aead.NonceSize():], nil)
}

func encrypt(t *testing.T, c sqlcrypter.Crypterer, plaintext []byte) []byte {
	t.Helper()

	out := new(bytes.Buffer)
	require.NoError(t, c.Encrypt(out, bytes.NewReader(plaintext)))

	return out.Bytes()
}

func decrypt(c sqlcrypter.Crypterer, blob []byte) ([]byte, error) {
	out := new(bytes.Buffer)
	if err := c.Decrypt(out, bytes.NewReader(blob)); err != nil {
		return nil, err
	}

	return out.Bytes(), nil
}

var compatPlaintexts = []struct {
	name      string
	plaintext []byte
}{
	{name: "empty", plaintext: []byte{}},
	{name: "short", plaintext: []byte("Hello World")},
	{name: "long", plaintext: bytes.Repeat([]byte("0123456789abcdef"), 4096)},
}

func Test_New_UsesRandomNonceAEAD(t *testing.T) {
	key, _ := sqlcrypter.GenerateBytes(32)

	c, err := New(key, nil)
	require.NoError(t, err)

	a, ok := c.(*AESCrypter)
	require.True(t, ok)

	// cipher.NewGCMWithRandomNonce reports a nonce size of 0 and an overhead of 28.
	// Under GOEXPERIMENT=boringcrypto the fallback cipher.NewGCM is used instead.
	if a.current.NonceSize() == 0 {
		assert.Equal(t, 28, a.current.Overhead())
	} else {
		assert.Equal(t, 12, a.current.NonceSize())
		assert.Equal(t, 16, a.current.Overhead())
	}
}

func Test_New_EmptyPreviousKeyIsInvalid(t *testing.T) {
	key, _ := sqlcrypter.GenerateBytes(32)

	_, err := New(key, []byte{})
	require.Error(t, err)
	assert.Contains(t, err.Error(), "previous DEK is invalid")
}

func Test_AESCrypter_OutputLayout(t *testing.T) {
	key, _ := sqlcrypter.GenerateBytes(32)
	c, err := New(key, nil)
	require.NoError(t, err)

	for _, tc := range compatPlaintexts {
		t.Run(tc.name, func(t *testing.T) {
			blob := encrypt(t, c, tc.plaintext)

			// nonce (12) || ciphertext || tag (16)
			assert.Len(t, blob, len(tc.plaintext)+28)
			if len(tc.plaintext) > 0 {
				assert.NotContains(t, string(blob), string(tc.plaintext))
			}

			got, err := decrypt(c, blob)
			require.NoError(t, err)
			assert.True(t, bytes.Equal(tc.plaintext, got), "plaintext mismatch")
		})
	}

	t.Run("unique nonce per call", func(t *testing.T) {
		first := encrypt(t, c, []byte("same"))
		second := encrypt(t, c, []byte("same"))
		assert.NotEqual(t, first, second)
		assert.NotEqual(t, first[:12], second[:12])
	})

	t.Run("tampered tag", func(t *testing.T) {
		blob := encrypt(t, c, []byte("Hello World"))
		blob[len(blob)-1] ^= 0x01

		_, err := decrypt(c, blob)
		require.Error(t, err)
		assert.Contains(t, err.Error(), "failed to decrypt ciphertext using current DEK")
	})

	t.Run("wrong key", func(t *testing.T) {
		otherKey, _ := sqlcrypter.GenerateBytes(32)
		other, err := New(otherKey, nil)
		require.NoError(t, err)

		_, err = decrypt(other, encrypt(t, c, []byte("Hello World")))
		require.Error(t, err)
	})
}

// Test_AESCrypter_LegacyCiphertext proves that data written by versions before
// v0.4.0 (caller-generated nonce) decrypts unchanged, because the stored layout
// is the same.
func Test_AESCrypter_LegacyCiphertext(t *testing.T) {
	key, _ := sqlcrypter.GenerateBytes(32)
	previousKey, _ := sqlcrypter.GenerateBytes(32)

	t.Run("current key", func(t *testing.T) {
		c, err := New(key, nil)
		require.NoError(t, err)

		for _, tc := range compatPlaintexts {
			t.Run(tc.name, func(t *testing.T) {
				got, err := decrypt(c, legacySeal(t, key, tc.plaintext))
				require.NoError(t, err)
				assert.True(t, bytes.Equal(tc.plaintext, got), "plaintext mismatch")
			})
		}
	})

	t.Run("previous key", func(t *testing.T) {
		c, err := New(key, previousKey)
		require.NoError(t, err)

		for _, tc := range compatPlaintexts {
			t.Run(tc.name, func(t *testing.T) {
				got, err := decrypt(c, legacySeal(t, previousKey, tc.plaintext))
				require.NoError(t, err)
				assert.True(t, bytes.Equal(tc.plaintext, got), "plaintext mismatch")
			})
		}
	})

	t.Run("previous key not configured", func(t *testing.T) {
		c, err := New(key, nil)
		require.NoError(t, err)

		_, err = decrypt(c, legacySeal(t, previousKey, []byte("Hello World")))
		require.Error(t, err)
		assert.Contains(t, err.Error(), "failed to decrypt ciphertext using current DEK")
		assert.NotContains(t, err.Error(), "previous")
	})
}

// Test_AESCrypter_PreviousReleaseReads proves the other direction: a reader
// built the way versions before v0.4.0 were (cipher.NewGCM, nonce split off
// the front) opens data this version writes, so a rollback loses nothing.
func Test_AESCrypter_PreviousReleaseReads(t *testing.T) {
	key, _ := sqlcrypter.GenerateBytes(32)
	c, err := New(key, nil)
	require.NoError(t, err)

	for _, tc := range compatPlaintexts {
		t.Run(tc.name, func(t *testing.T) {
			got, err := legacyOpen(t, key, encrypt(t, c, tc.plaintext))
			require.NoError(t, err)
			assert.True(t, bytes.Equal(tc.plaintext, got), "plaintext mismatch")
		})
	}
}

type failingWriter struct{}

func (failingWriter) Write([]byte) (int, error) { return 0, io.ErrClosedPipe }

func Test_AESCrypter_WriteErrors(t *testing.T) {
	key, _ := sqlcrypter.GenerateBytes(32)
	c, err := New(key, nil)
	require.NoError(t, err)

	err = c.Encrypt(failingWriter{}, bytes.NewReader([]byte("Hello World")))
	require.ErrorIs(t, err, io.ErrClosedPipe)
	assert.Contains(t, err.Error(), "failed to write ciphertext")

	err = c.Decrypt(failingWriter{}, bytes.NewReader(encrypt(t, c, []byte("Hello World"))))
	require.ErrorIs(t, err, io.ErrClosedPipe)
	assert.Contains(t, err.Error(), "failed to write plaintext")
}
